# -*- coding: utf-8 -*-

import numpy as np
from qiskit_metal import draw, Dict
from qiskit_metal.qlibrary.core import QComponent

class FCQubitPocket(QComponent):
    """Generic qubit capacitor pocket with antennas and local ground cutout.

    Builds a reusable pocket primitive for lumped-element qubits, including two
    capacitor pads (signal/ground), JJ landing arms with fillet cutouts, a resonator
    antenna and a charge/drive antenna (each with a straight CPW), and a local ground
    region where the pocket is subtracted from the ground plane.

    Converted to Qiskit Metal with Carve-Out feature support and specific GDS layer 
    targeting for flip-chip architectures.
    """

    component_metadata = Dict(short_name='QubitPocket',
                              _qgeometry_table_poly='True',
                              _qgeometry_table_path='True',
                              _qgeometry_table_junction='True')
    """Component metadata"""

    default_options = Dict(
        # Resonator antenna
        res_antenna_width='160um',
        res_antenna_height='60um',
        res_antenna_offset_x='0um',
        res_antenna_offset_y='160um',
        res_straight_len='200um',
        res_straight_width='10um',
        res_straight_gap='6um',
        res_antenna_radius='5um',

        # Charge antenna
        charge_antenna_width='20um',
        charge_antenna_height='60um',
        charge_antenna_offset_x='0um',
        charge_antenna_offset_y='-160um',
        charge_straight_len='200um',
        charge_straight_width='10um',
        charge_straight_gap='6um',
        charge_antenna_radius='5um',

        # Qubit pocket geometry (calculated from original multipliers)
        qb_cap_spacing='60.5um',  # 55.0 * 1.1
        qb_cap_width='630.0um',   # 700.0 * 0.9
        qb_cap_height='170.0um',  # 200.0 * 0.85
        jj_gap='18.0um',          # 15.0 * 1.2
        jj_arm_width='8.0um',
        qb_nofill_extent='120.0um', # 100.0 * 1.2

        # Corner / fillet / nofill geometry
        cap_radius='10.0um',      # 20.0 * 0.5
        fillet_radius='10.0um',
        nofill_pad='12.0um',
        nofill_radius_small='10.0um',
        nofill_radius_big='30.0um',

        # Qiskit Metal specific parameters (Chips)
        chip='main',
        carve_out_chip='Q_chip',
        carve_out_pocket_extend='10um',  # Extension size for the main pocket and antennas
        carve_out_cpw_extend='5um',      # Extension size specifically for the CPW straight regions
        
        # Dedicated Layer Mapping
        layer_qub_sig=5,      # QM1F_qubsig (Top Pad)
        layer_qub_gnd=6,      # QM1F_qubgnd (Bottom Pad)
        layer_cpw_sig=1,      # QM1F_cpwsig (Antennas / CPW center trace)
        layer_gen_gnd=8,      # QM1F_gengnd (Main pocket / nofill subtract)
        layer_carve_out=108   # IM1F_gengnd (Carve out subtract on opposite chip)
    )
    """Default drawing options"""

    def make(self):
        """Build the component."""
        p = self.p

        # ---------------------------------------------------------------------
        # Derived Dimensions
        # ---------------------------------------------------------------------
        cap_u_center_y = (p.qb_cap_spacing + p.qb_cap_height) / 2.0
        cap_d_center_y = -cap_u_center_y
        arm_len = (p.qb_cap_spacing - p.jj_gap) / 2.0

        # ---------------------------------------------------------------------
        # Top capacitor (signal) + arm + fillet cutouts
        # ---------------------------------------------------------------------
        # Cap pad (Rounded via buffer trick)
        cap_u = draw.rectangle(p.qb_cap_width, p.qb_cap_height, 0, cap_u_center_y)
        cap_u = cap_u.buffer(-p.cap_radius).buffer(p.cap_radius)

        # Arm
        arm_u_y = cap_u_center_y - p.qb_cap_height / 2.0 - arm_len / 2.0
        arm_u = draw.rectangle(p.jj_arm_width, arm_len, 0, arm_u_y)

        # Fillets (Manually constructed via subtraction to create a concave curve)
        f_y = cap_u_center_y - p.qb_cap_height / 2.0
        rect_f = draw.rectangle(p.jj_arm_width + 2 * p.fillet_radius, p.fillet_radius, 0, f_y - p.fillet_radius / 2.0)
        circ_r = draw.Point(p.jj_arm_width / 2.0 + p.fillet_radius, f_y - p.fillet_radius).buffer(p.fillet_radius)
        circ_l = draw.Point(-p.jj_arm_width / 2.0 - p.fillet_radius, f_y - p.fillet_radius).buffer(p.fillet_radius)
        
        fillet_u = draw.subtract(rect_f, circ_r)
        fillet_u = draw.subtract(fillet_u, circ_l)

        # Merge Top Half
        top_half = draw.union([cap_u, arm_u, fillet_u])

        # ---------------------------------------------------------------------
        # Bottom capacitor (ground) + arm + fillet cutouts
        # ---------------------------------------------------------------------
        # Easily generated by rotating the top half 180 degrees around the origin
        bot_half = draw.rotate(top_half, 180, origin=(0, 0))

        # ---------------------------------------------------------------------
        # Josephson Junction
        # ---------------------------------------------------------------------
        rect_jj = draw.LineString([(0, p.jj_gap / 2.0), (0, -p.jj_gap / 2.0)])

        # ---------------------------------------------------------------------
        # Resonator antenna + straight + local nofill
        # ---------------------------------------------------------------------
        res_x = p.res_antenna_offset_x
        res_y = cap_u_center_y + p.qb_cap_height / 2.0 + p.res_antenna_height / 2.0 + p.res_antenna_offset_y

        res_ant = draw.rectangle(p.res_antenna_width, p.res_antenna_height, res_x, res_y)
        res_ant = res_ant.buffer(-p.res_antenna_radius).buffer(p.res_antenna_radius)

        res_straight = draw.LineString([
            (res_x, res_y + p.res_antenna_height / 2.0), 
            (res_x, res_y + p.res_antenna_height / 2.0 + p.res_straight_len)
        ])

        res_nofill = draw.rectangle(p.res_antenna_width + p.nofill_pad, 
                                    p.res_antenna_height + p.nofill_pad, res_x, res_y)
        res_nofill = res_nofill.buffer(-p.nofill_radius_small).buffer(p.nofill_radius_small)

        # ---------------------------------------------------------------------
        # Charge antenna + straight + local nofill
        # ---------------------------------------------------------------------
        chg_x = p.charge_antenna_offset_x
        chg_y = cap_d_center_y - p.qb_cap_height / 2.0 - p.charge_antenna_height / 2.0 + p.charge_antenna_offset_y

        chg_ant = draw.rectangle(p.charge_antenna_width, p.charge_antenna_height, chg_x, chg_y)
        chg_ant = chg_ant.buffer(-p.charge_antenna_radius).buffer(p.charge_antenna_radius)

        chg_straight = draw.LineString([
            (chg_x, chg_y - p.charge_antenna_height / 2.0), 
            (chg_x, chg_y - p.charge_antenna_height / 2.0 - p.charge_straight_len)
        ])

        chg_nofill = draw.rectangle(p.charge_antenna_width + p.nofill_pad, 
                                    p.charge_antenna_height + p.nofill_pad, chg_x, chg_y)
        chg_nofill = chg_nofill.buffer(-p.nofill_radius_small).buffer(p.nofill_radius_small)

        # ---------------------------------------------------------------------
        # Global pocket nofill
        # ---------------------------------------------------------------------
        pocket_w = p.qb_cap_width + 2.0 * p.qb_nofill_extent
        pocket_h = p.qb_cap_spacing + 2.0 * p.qb_cap_height + 2.0 * p.qb_nofill_extent
        pocket = draw.rectangle(pocket_w, pocket_h, 0, 0)
        pocket = pocket.buffer(-p.nofill_radius_big).buffer(p.nofill_radius_big)

        # ---------------------------------------------------------------------
        # Conditional Carve-out Logic (Separated CPW and Pocket)
        # ---------------------------------------------------------------------
        do_carve_out = bool(p.carve_out_chip and str(p.carve_out_chip).strip().lower() != 'none')

        if do_carve_out:
            # Buffer the paths to convert them into polygons matching their subtract widths
            res_straight_sub = res_straight.buffer((p.res_straight_width + 2 * p.res_straight_gap) / 2.0, cap_style=2)
            chg_straight_sub = chg_straight.buffer((p.charge_straight_width + 2 * p.charge_straight_gap) / 2.0, cap_style=2)

            # Group 1: Main pocket and antenna no-fills
            pocket_group = draw.union([pocket, res_nofill, chg_nofill])
            pocket_carve = pocket_group.buffer(p.carve_out_pocket_extend)
            
            # Group 2: CPW straight sections
            cpw_group = draw.union([res_straight_sub, chg_straight_sub])
            cpw_carve = cpw_group.buffer(p.carve_out_cpw_extend)

            # Combine groups to form final carve-out footprint
            carve_out = draw.union([pocket_carve, cpw_carve])

        # ---------------------------------------------------------------------
        # Rotate and Translate
        # ---------------------------------------------------------------------
        c_items = [top_half, bot_half, rect_jj, res_ant, chg_ant, res_straight, chg_straight, pocket, res_nofill, chg_nofill]
        if do_carve_out:
            c_items.append(carve_out)

        c_items = draw.rotate(c_items, p.orientation, origin=(0, 0))
        c_items = draw.translate(c_items, p.pos_x, p.pos_y)

        if do_carve_out:
            [top_half, bot_half, rect_jj, res_ant, chg_ant, res_straight, chg_straight, pocket, res_nofill, chg_nofill, carve_out] = c_items
        else:
            [top_half, bot_half, rect_jj, res_ant, chg_ant, res_straight, chg_straight, pocket, res_nofill, chg_nofill] = c_items

        # ---------------------------------------------------------------------
        # Add to QGeometry Tables (Layer specific)
        # ---------------------------------------------------------------------
        # Signal / Pad Geometries
        self.add_qgeometry('poly', {'top_pad': top_half}, layer=p.layer_qub_sig, chip=p.chip)
        self.add_qgeometry('poly', {'bot_pad': bot_half}, layer=p.layer_qub_gnd, chip=p.chip)
        self.add_qgeometry('poly', {'res_ant': res_ant, 'chg_ant': chg_ant}, layer=p.layer_cpw_sig, chip=p.chip)
        
        # Path lines
        self.add_qgeometry('path', {'res_straight': res_straight}, width=p.res_straight_width, layer=p.layer_cpw_sig, chip=p.chip)
        self.add_qgeometry('path', {'chg_straight': chg_straight}, width=p.charge_straight_width, layer=p.layer_cpw_sig, chip=p.chip)

        # Subtractions (Ground cutouts)
        self.add_qgeometry('poly', {'pocket': pocket, 'res_nofill': res_nofill, 'chg_nofill': chg_nofill}, 
                           subtract=True, layer=p.layer_gen_gnd, chip=p.chip)
        
        self.add_qgeometry('path', {'res_straight_sub': res_straight}, width=p.res_straight_width + 2*p.res_straight_gap, 
                           subtract=True, layer=p.layer_cpw_sig, chip=p.chip)
        self.add_qgeometry('path', {'chg_straight_sub': chg_straight}, width=p.charge_straight_width + 2*p.charge_straight_gap, 
                           subtract=True, layer=p.layer_cpw_sig, chip=p.chip)

        # Junction
        self.add_qgeometry('junction', {'rect_jj': rect_jj}, width=p.jj_arm_width, chip=p.chip)

        # Carve Out Shape (Targeting the opposing chip's general ground layer)
        if do_carve_out:
            self.add_qgeometry('poly', {'carve_out': carve_out}, 
                               subtract=True, chip=p.carve_out_chip, layer=p.layer_carve_out)

        # ---------------------------------------------------------------------
        # Add Pins
        # ---------------------------------------------------------------------
        # CPW Connectors
        self.add_pin('res_o2', points=np.array(res_straight.coords), width=p.res_straight_width, input_as_norm=True)
        self.add_pin('charge_o2', points=np.array(chg_straight.coords), width=p.charge_straight_width, input_as_norm=True)